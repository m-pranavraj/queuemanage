let currentLang: Language = (localStorage.getItem("zp_language") as any) || "en";
const listeners = new Set<() => void>();

export function useTranslation() {
  const [, setTick] = useState(0);

  useEffect(() => {
    const listener = () => setTick((t) => t + 1);
    listeners.add(listener);
    return () => {
      listeners.delete(listener);
    };
  }, []);

  const changeLanguage = (newLang: Language) => {
    currentLang = newLang;
    localStorage.setItem("zp_language", newLang);
    listeners.forEach((l) => l());
  };

  const t = (key: keyof typeof translations["en"] | string): string => {
    const dict = translations[currentLang] || translations["en"];
    return (dict as any)[key] || (translations["en"] as any)[key] || key;
  };

  return { t, lang: currentLang, changeLanguage };
}
